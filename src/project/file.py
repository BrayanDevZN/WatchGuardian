"""Copy WatchGuardian and create a starter project scaffold."""

import json
import shutil
from pathlib import Path

from WatchGuardian import WatchLogs
from src.project.settings import DEFAULT_CONFIGS


_MAIN_TEMPLATE = '''"""Project entry point generated by WatchGuardian."""

import asyncio
import json
from pathlib import Path

from src.project.module import WatchModule
from src.project.settings import ProjectSettings


class ProjectApp:
    """Load project settings and initialize all WatchGuardian modules."""

    def __init__(self) -> None:
        self.settings_path = Path(__file__).with_name("settings.json")
        with self.settings_path.open(encoding="utf-8") as settings_file:
            self.project_config = json.load(settings_file)

        self.name = self.project_config.get("name", "WatchGuardian")
        self.local = True
        self.http = None
        self.settings = None
        self.module = None

    async def load_module(self):
        """Apply JSON configs, initialize modules, and return WatchModule."""
        env_file = self.project_config.get("env_file")
        if env_file is not None:
            env_path = Path(env_file)
            if not env_path.is_absolute():
                env_file = str(self.settings_path.parent / env_path)

        self.local = env_file is None
        self.http = None if self.local else True

        project_settings = ProjectSettings(
            env_file=env_file,
            local=self.local,
        )
        self.settings = project_settings.get()

        for name, value in self.project_config.get("configs", {}).items():
            self.settings.add_config({"name": name, "value": value})

        self.module = WatchModule(
            settings=self.settings,
            http=self.http,
            loglevel=self.project_config.get("loglevel", "INFO"),
        )
        await self.module.load_modules()
        return self.module


app = ProjectApp()


if __name__ == "__main__":
    asyncio.run(app.load_module())
'''


def copy_watchguardian(
    path: str | Path | None = None,
    name: str | None = None,
    env_file: str | Path | None = None,
) -> Path:
    """Copy WatchGuardian and generate settings.json and main.py.

    If path is omitted, the current working directory is used. If name is
    omitted, the copied folder keeps the default name, WatchGuardian.
    Without env_file, the generated project uses local defaults.
    """
    logger = WatchLogs()
    source = Path(__file__).resolve().parents[2] / "WatchGuardian"
    destination_root = Path(path) if path is not None else Path.cwd()
    folder_name = "WatchGuardian" if name is None else name

    if (
        not folder_name
        or Path(folder_name).name != folder_name
        or folder_name in {".", ".."}
    ):
        error = ValueError("name must be a non-empty folder name, not a path.")
        logger.error(str(error))
        raise error

    destination = destination_root / folder_name

    logger.info(f"Preparing to copy WatchGuardian from '{source}'.")

    if not source.is_dir():
        error = FileNotFoundError(f"WatchGuardian source folder was not found: {source}")
        logger.error(str(error))
        raise error

    if destination.resolve() == source.resolve():
        error = ValueError("The destination cannot be the WatchGuardian source folder.")
        logger.error(str(error))
        raise error

    logger.info(f"Copying WatchGuardian to '{destination}'.")

    try:
        destination_root.mkdir(parents=True, exist_ok=True)
        shutil.copytree(source, destination)

        use_local_settings = env_file is None
        project_settings = {
            "name": folder_name,
            "path": str(destination.resolve()),
            "env_file": str(env_file) if env_file is not None else None,
            "local": use_local_settings,
            "http": None if use_local_settings else True,
            "loglevel": "INFO",
            "configs": DEFAULT_CONFIGS,
        }

        (destination / "settings.json").write_text(
            json.dumps(project_settings, indent=4) + "\n",
            encoding="utf-8",
        )
        (destination / "main.py").write_text(
            _MAIN_TEMPLATE,
            encoding="utf-8",
        )
    except Exception as error:
        logger.error(f"Failed to create the WatchGuardian project: {error}")
        raise

    logger.success(f"WatchGuardian project created at '{destination}'.")
    return destination
